
-- Store metadata for photos attached to handoffs.
-- Image files themselves remain in Supabase Storage.

CREATE TABLE IF NOT EXISTS public.handoff_photos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  handoff_id bigint NOT NULL
    REFERENCES public.handoffs(id) ON DELETE CASCADE,
  storage_path text NOT NULL UNIQUE,
  content_type text NOT NULL DEFAULT 'image/jpeg',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_handoff_photos_handoff_id
  ON public.handoff_photos(handoff_id);

COMMENT ON TABLE public.handoff_photos IS
  'Metadata for image attachments associated with shift handoffs.';
