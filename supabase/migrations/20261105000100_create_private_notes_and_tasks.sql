-- ------------------------------------------------------------------------------
-- 1. AUTHORISED PRIVATE USERS TABLE & HELPER FUNCTION
-- ------------------------------------------------------------------------------
-- Only three authorised people are allowed to access private functionality:
-- 1. Geet
-- 2. Nikhil
-- 3. Parul (Geet's sister)
--
-- Each person must have their own separate Supabase auth.users account.
-- This allowlist links their Supabase auth user UUIDs to their authorised identity.

CREATE TABLE IF NOT EXISTS public.authorized_private_users (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email text UNIQUE NOT NULL,
  name text NOT NULL CHECK (name IN ('Geet', 'Nikhil', 'Parul')),
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.authorized_private_users IS
'Allowlist of individual authenticated users permitted to access private notes and private tasks.';

-- Helper function to verify if the current authenticated caller is on the private allowlist
CREATE OR REPLACE FUNCTION public.is_authorized_private_user()
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
SET search_path = ''
STABLE
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.authorized_private_users
    WHERE id = auth.uid()
  );
$$;

COMMENT ON FUNCTION public.is_authorized_private_user() IS
'Returns true if the current authenticated caller (auth.uid()) belongs to an active authorised private user (Geet, Nikhil, or Parul).';

-- Restrict function execution: revoke PUBLIC and anon access, grant to authenticated only
REVOKE EXECUTE ON FUNCTION public.is_authorized_private_user() FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.is_authorized_private_user() FROM anon;
GRANT EXECUTE ON FUNCTION public.is_authorized_private_user() TO authenticated;

