-- Policies for authorized_private_users:
-- An authenticated user can only view their own allowlist profile
DROP POLICY IF EXISTS "Allow users to view own allowlist profile" ON public.authorized_private_users;
CREATE POLICY "Allow users to view own allowlist profile"
  ON public.authorized_private_users
  FOR SELECT
  TO authenticated
  USING (auth.uid() = id);

-- Policies for private_notes:
-- Creator owns the record, must be on allowlist, and user_id must match auth.uid()
DROP POLICY IF EXISTS "Allow authorized user to select own private notes" ON public.private_notes;
CREATE POLICY "Allow authorized user to select own private notes"
  ON public.private_notes
  FOR SELECT
  TO authenticated
  USING (
    auth.uid() = user_id
    AND public.is_authorized_private_user()
  );

